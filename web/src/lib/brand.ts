/**
 * Client mirror of api/src/workspaces/brand.ts (header name, legal footer lines) so the
 * Settings preview shows exactly what the PDF prints before anything is saved.
 */
import type { Brand } from "./types";

export const MAX_LOGO_BYTES = 256 * 1024;
export const LOGO_TYPES = ["image/png", "image/jpeg"] as const;

export function headerName(b: Brand): string | null {
  return b.name || b.trading_name || b.legal_name || null;
}

export function legalLines(b: Brand): string[] {
  if (!b.legal_name) return [];
  const id = [
    b.trading_name && b.trading_name !== b.legal_name
      ? `${b.legal_name} (trading as ${b.trading_name})`
      : b.legal_name,
    b.company_number ? `Company no. ${b.company_number}` : null,
  ]
    .filter(Boolean)
    .join(" · ");
  const lines = [id];
  const address = (b.registered_address ?? "")
    .split(/\r?\n/)
    .map((l) => l.trim())
    .filter(Boolean);
  if (address.length) lines.push(`Registered office: ${address.join(", ")}`);
  const contact = [b.contact_email, b.website?.replace(/^https?:\/\//i, "")]
    .filter(Boolean)
    .join(" · ");
  if (contact) lines.push(contact);
  return lines;
}

export function footerLines(b: Brand): string[] {
  const lines = legalLines(b);
  if (b.footer) lines.push(b.footer);
  if (!lines.length) lines.push("Generated by Spider");
  return lines;
}

/** Client-side check before upload; the API re-checks the bytes. */
export function logoProblem(file: {
  type: string;
  size: number;
}): string | null {
  if (!(LOGO_TYPES as readonly string[]).includes(file.type))
    return "The logo must be a PNG or JPEG image.";
  if (file.size > MAX_LOGO_BYTES)
    return `The logo is larger than ${MAX_LOGO_BYTES / 1024} KB.`;
  if (file.size === 0) return "The logo file is empty.";
  return null;
}

/** Trims every field and drops empty ones, like the API does before storing. */
export function cleanBrand(b: Brand): Brand {
  const out: Brand = {};
  for (const [k, v] of Object.entries(b) as [
    keyof Brand,
    string | undefined,
  ][]) {
    const t =
      k === "registered_address"
        ? (v ?? "").trim()
        : (v ?? "").replace(/\s+/g, " ").trim();
    if (t) out[k] = t;
  }
  return out;
}
