import { describe, expect, it } from "vitest";
import {
  cleanBrand,
  footerLines,
  headerName,
  legalLines,
  logoProblem,
} from "./brand";

describe("brand preview helpers", () => {
  it("prints the same legal lines as the PDF", () => {
    expect(
      legalLines({
        legal_name: "MISSIRIA LTD",
        trading_name: "MISSIRIA",
        company_number: "17494304",
        registered_address:
          "Unit A, 82 James Carter Road\n\nMildenhall IP28 7DE",
        contact_email: "contact@missiria.dev",
        website: "https://www.missiria.dev",
      }),
    ).toEqual([
      "MISSIRIA LTD (trading as MISSIRIA) · Company no. 17494304",
      "Registered office: Unit A, 82 James Carter Road, Mildenhall IP28 7DE",
      "contact@missiria.dev · www.missiria.dev",
    ]);
  });

  it("text-only fallbacks", () => {
    expect(headerName({})).toBeNull();
    expect(headerName({ legal_name: "L" })).toBe("L");
    expect(footerLines({})).toEqual(["Generated by Spider"]);
    expect(
      footerLines({ footer: "Confidential", company_number: "1" }),
    ).toEqual(["Confidential"]);
  });

  it("checks the logo type and size before uploading", () => {
    expect(logoProblem({ type: "image/svg+xml", size: 10 })).toMatch(
      /PNG or JPEG/,
    );
    expect(logoProblem({ type: "image/png", size: 300 * 1024 })).toMatch(
      /larger than 256 KB/,
    );
    expect(logoProblem({ type: "image/jpeg", size: 0 })).toMatch(/empty/);
    expect(logoProblem({ type: "image/png", size: 2048 })).toBeNull();
  });

  it("drops blank fields like the API", () => {
    expect(
      cleanBrand({
        name: "  A  B ",
        footer: "   ",
        registered_address: " x\ny ",
      }),
    ).toEqual({ name: "A B", registered_address: "x\ny" });
  });
});
