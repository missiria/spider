/**
 * Readable PDF for a report (pdfmake, pure JS — no browser). Sections mirror the data
 * endpoint; every table carries definitions, period, freshness and coverage notes.
 *
 * MISS-0135: every page carries the workspace's header (approved logo at its own aspect
 * ratio + brand name, or text only) and a footer with the legal entity lines, the generation
 * date and "Page x of y". Page margins are computed from what the header and footer print,
 * so neither can overlap the body.
 */
import type {
  TDocumentDefinitions,
  Content,
  TableCell,
} from 'pdfmake/interfaces';
import { Brand, StoredLogo, headerName, legalLines } from '../workspaces/brand';
import { ReportData } from './reports.service';

export type { Brand };

/** Rows a PDF table prints; the CSV carries the full list. */
export const PDF_TABLE_ROWS = 50;

const PAGE_WIDTH = 595.28; // A4 in points
const SIDE = 36;
/** max logo box in the header; the image is fitted inside, never stretched */
export const LOGO_BOX = { width: 140, height: 28 };
const HEADER_TOP = 22;
const HEADER_GAP = 14; // clear space between the header rule and the body
const FOOTER_FONT = 7.5;
const FOOTER_LINE = 10; // line height for the footer font (pdfmake ≈ 1.17 × font size + leading)
/** characters per footer line at FOOTER_FONT across the printable width (Roboto ≈ 0.5 em) */
const FOOTER_CHARS = Math.floor((PAGE_WIDTH - 2 * SIDE) / (FOOTER_FONT * 0.5));

/** The embedded Roboto has no arrow glyph: print ranges with an en dash instead of a box. */
const pdfText = (s: string) => s.replace(/\s*→\s*/g, ' – ');

/** Logo size in points inside LOGO_BOX, keeping the image's aspect ratio. */
export function fitLogo(
  width: number,
  height: number,
): { width: number; height: number } {
  const scale = Math.min(LOGO_BOX.width / width, LOGO_BOX.height / height);
  return {
    width: Math.round(width * scale * 100) / 100,
    height: Math.round(height * scale * 100) / 100,
  };
}

/** Footer lines in print order: legal entity lines, free footer line, then date + page. */
export function footerLines(brand: Brand): string[] {
  const lines = legalLines(brand);
  if (brand.footer) lines.push(brand.footer);
  if (!lines.length) lines.push('Generated by Spider');
  return lines;
}

/** Wrapped line count of the footer, used to reserve the bottom margin. */
export function footerHeight(lines: string[]): number {
  const wrapped = lines.reduce(
    (n, l) => n + Math.max(1, Math.ceil(l.length / FOOTER_CHARS)),
    0,
  );
  // + 1 line for "Generated … · Page x of y", + the rule and paddings
  return (wrapped + 1) * FOOTER_LINE + 22;
}

const fmtInt = (n: number) =>
  new Intl.NumberFormat('en-US').format(Math.round(n));
const fmtPct = (r: number) => `${(r * 100).toFixed(2)}%`;
const fmtPos = (p: number) => (p ? p.toFixed(1) : '—');
const fmtDelta = (d: number | null) =>
  d === null
    ? '—'
    : `${Math.round(d * 100) > 0 ? '+' : ''}${Math.round(d * 100)}%`;

export function buildReportDocument(
  data: ReportData,
  brand: Brand = {},
  logo: StoredLogo | null = null,
): TDocumentDefinitions {
  const accent = /^#[0-9a-f]{6}$/i.test(brand.accent_color ?? '')
    ? (brand.accent_color as string)
    : '#4f46e5';
  const content: Content[] = [];
  const name = headerName(brand);
  const logoSize = logo ? fitLogo(logo.width, logo.height) : null;
  const headerHeight = Math.max(logoSize?.height ?? 0, 14);
  const topMargin = HEADER_TOP + headerHeight + 6 + HEADER_GAP;
  const footer = footerLines(brand);
  const bottomMargin = footerHeight(footer);
  const generated = data.generated_at.slice(0, 10);

  content.push({
    text: 'Search performance report',
    style: 'brand',
    color: accent,
  });
  content.push({ text: data.title, style: 'h1' });
  content.push({
    text: pdfText(
      `${data.period.start} → ${data.period.end}  vs  ${data.previousPeriod.start} → ${data.previousPeriod.end}`,
    ),
    style: 'muted',
  });
  content.push({
    text: `Generated ${data.generated_at.slice(0, 16).replace('T', ' ')} UTC · GSC data through ${data.data_through ?? 'n/a'} · Source: Google Search Console (web search)`,
    style: 'muted',
    margin: [0, 0, 0, 12],
  });
  if (data.notes)
    content.push({ text: pdfText(data.notes), margin: [0, 0, 0, 10] });

  if (data.overview) {
    const o = data.overview;
    const noPrev = o.comparison_available === false;
    content.push({ text: 'Overview', style: 'h2', color: accent });
    if (o.note) content.push({ text: o.note, style: 'muted' });
    if (noPrev)
      content.push({
        text: 'No stored rows for the comparison period: previous values and changes are not shown.',
        style: 'muted',
      });
    content.push(
      kpiTable([
        [
          'Clicks',
          fmtInt(o.current.clicks),
          noPrev ? '—' : fmtInt(o.previous.clicks),
          fmtDelta(o.delta.clicks),
        ],
        [
          'Impressions',
          fmtInt(o.current.impressions),
          noPrev ? '—' : fmtInt(o.previous.impressions),
          fmtDelta(o.delta.impressions),
        ],
        [
          'CTR',
          fmtPct(o.current.ctr),
          noPrev ? '—' : fmtPct(o.previous.ctr),
          fmtDelta(o.delta.ctr),
        ],
        [
          'Avg. position',
          fmtPos(o.current.position),
          noPrev ? '—' : fmtPos(o.previous.position),
          fmtDelta(o.delta.position),
        ],
      ]),
    );
    if (o.properties) {
      content.push({ text: 'Per property', style: 'h3' });
      content.push(
        dataTable(
          ['Site', 'Clicks', 'Δ', 'Impressions', 'Δ', 'CTR', 'Position'],
          o.properties.map((p) => [
            p.display_name,
            fmtInt(p.current.clicks),
            fmtDelta(p.delta.clicks),
            fmtInt(p.current.impressions),
            fmtDelta(p.delta.impressions),
            fmtPct(p.current.ctr),
            fmtPos(p.current.position),
          ]),
          ['*', 'auto', 'auto', 'auto', 'auto', 'auto', 'auto'],
        ),
      );
    }
  }

  for (const section of data.tables) {
    content.push({
      text: section.title,
      style: 'h2',
      color: accent,
      pageBreak: section.rows.length > 20 ? 'before' : undefined,
    });
    if (section.note)
      content.push({ text: pdfText(section.note), style: 'muted' });
    if (!section.rows.length) {
      content.push({
        text: 'No rows for this period.',
        style: 'muted',
        margin: [0, 0, 0, 8],
      });
      continue;
    }
    if (section.rows.length > PDF_TABLE_ROWS)
      content.push({
        text: `First ${PDF_TABLE_ROWS} of ${section.rows.length} rows; the CSV export has all of them.`,
        style: 'muted',
      });
    content.push(
      dataTable(
        [section.keyLabel, 'Clicks', 'Impressions', 'CTR', 'Position'],
        section.rows
          .slice(0, PDF_TABLE_ROWS)
          .map((r) => [
            r.key,
            fmtInt(r.clicks),
            fmtInt(r.impressions),
            fmtPct(r.ctr),
            fmtPos(r.position),
          ]),
        ['*', 'auto', 'auto', 'auto', 'auto'],
      ),
    );
  }

  if (data.opportunities) {
    content.push({
      text: 'Open opportunities',
      style: 'h2',
      color: accent,
      pageBreak: 'before',
    });
    content.push({
      text: 'Measured changes and heuristics from the stored Search Console data. Nothing here is a confirmed cause or a Google penalty.',
      style: 'muted',
    });
    if (!data.opportunities.length)
      content.push({ text: 'None open.', style: 'muted' });
    else {
      if (data.opportunities.length > PDF_TABLE_ROWS)
        content.push({
          text: `First ${PDF_TABLE_ROWS} of ${data.opportunities.length} opportunities; the CSV export has all of them.`,
          style: 'muted',
        });
      content.push(
        dataTable(
          ['Priority', 'Finding', 'Property', 'Confidence'],
          data.opportunities
            .slice(0, PDF_TABLE_ROWS)
            .map((o) => [o.priority, o.title, o.property, o.confidence]),
          ['auto', '*', 'auto', 'auto'],
        ),
      );
    }
  }

  content.push({
    text: 'Definitions',
    style: 'h2',
    color: accent,
    pageBreak: 'before',
  });
  content.push({
    ul: [
      'Clicks / impressions: sums over the period as reported by Google Search Console for the property.',
      'CTR: Σ clicks / Σ impressions over the period (not an average of daily CTRs).',
      'Average position: impressions-weighted mean of daily average positions; lower is better.',
      'Δ: change versus the previous period of the same length ending the day before the period starts; "—" when the previous value is 0.',
      'Query tables cover only queries Google reports; low-volume ("anonymised") queries are omitted, so query rows explain less than 100 % of clicks — the coverage note under each table states how much.',
      'Search appearance rows exist only for results with a special appearance (rich results, AMP…).',
      'Data freshness: Google finalises data about three days late; the report ends at "data through".',
    ],
    style: 'small',
  });

  const headerContent: Content[] = [];
  if (logo && logoSize)
    headerContent.push({
      image: `data:${logo.mime};base64,${logo.data}`,
      width: logoSize.width,
      height: logoSize.height,
    });
  // with a logo the name prints beside it only when it adds information (no duplicate wordmark)
  if (name && !logo)
    headerContent.push({ text: name, style: 'headerName', color: accent });
  else if (name && logo)
    headerContent.push({
      text: name,
      style: 'headerSub',
      margin: [12, Math.max(0, logoSize!.height / 2 - 5), 0, 0],
    });
  if (!headerContent.length)
    headerContent.push({
      text: 'Search performance report',
      style: 'headerSub',
    });

  return {
    pageSize: 'A4',
    pageMargins: [SIDE, topMargin, SIDE, bottomMargin],
    info: {
      title: data.title,
      author: name ?? undefined,
      creator: 'Spider',
    },
    header: (): Content => ({
      margin: [SIDE, HEADER_TOP, SIDE, 0],
      stack: [
        {
          columns: headerContent.map(
            (c) => ({ width: 'auto', stack: [c] }) as Content,
          ),
          columnGap: 0,
        } as Content,
        <Content>{
          canvas: [
            {
              type: 'line',
              x1: 0,
              y1: 6,
              x2: PAGE_WIDTH - 2 * SIDE,
              y2: 6,
              lineWidth: 0.5,
              lineColor: '#e2e8f0',
            },
          ],
        },
      ],
    }),
    footer: (page: number, pages: number): Content => ({
      margin: [SIDE, 10, SIDE, 0],
      stack: [
        <Content>{
          canvas: [
            {
              type: 'line',
              x1: 0,
              y1: 0,
              x2: PAGE_WIDTH - 2 * SIDE,
              y2: 0,
              lineWidth: 0.5,
              lineColor: '#e2e8f0',
            },
          ],
          margin: [0, 0, 0, 4],
        },
        ...footer.map((t): Content => ({ text: t, style: 'footer' })),
        <Content>{
          columns: [
            { text: `Generated ${generated}`, style: 'footer' },
            {
              text: `Page ${page} of ${pages}`,
              alignment: 'right',
              style: 'footer',
            },
          ],
        },
      ],
    }),
    content,
    styles: {
      brand: { fontSize: 10, bold: true, margin: [0, 0, 0, 4] },
      h1: { fontSize: 20, bold: true, margin: [0, 0, 0, 4] },
      h2: { fontSize: 14, bold: true, margin: [0, 14, 0, 6] },
      h3: { fontSize: 11, bold: true, margin: [0, 10, 0, 4] },
      muted: { fontSize: 9, color: '#64748b', margin: [0, 0, 0, 6] },
      small: { fontSize: 9 },
      th: { bold: true, fontSize: 9, fillColor: '#f1f5f9' },
      td: { fontSize: 9 },
      footer: { fontSize: FOOTER_FONT, color: '#64748b', lineHeight: 1.1 },
      headerName: { fontSize: 12, bold: true },
      headerSub: { fontSize: 9, color: '#475569', bold: true },
    },
    defaultStyle: { fontSize: 10 },
  };
}

function kpiTable(rows: string[][]): Content {
  return {
    table: {
      headerRows: 1,
      widths: ['*', 'auto', 'auto', 'auto'],
      body: [
        cells(['Metric', 'Current', 'Previous', 'Δ'], 'th'),
        ...rows.map((r) => cells(r, 'td')),
      ],
    },
    layout: 'lightHorizontalLines',
    margin: [0, 0, 0, 8],
  };
}

function dataTable(
  headers: string[],
  rows: string[][],
  widths: (string | number)[],
): Content {
  return {
    table: {
      headerRows: 1,
      dontBreakRows: true,
      widths,
      body: [cells(headers, 'th'), ...rows.map((r) => cells(r, 'td'))],
    },
    layout: 'lightHorizontalLines',
    margin: [0, 0, 0, 8],
  };
}

function cells(values: string[], style: string): TableCell[] {
  return values.map((v, i) => ({
    text: v,
    style,
    alignment: i === 0 ? 'left' : 'right',
    noWrap: false,
  }));
}
